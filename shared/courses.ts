export const findCourse = (id: string) => COURSES.find((c) => c.id === id);

export const courseLessonCount = (c: CourseDef) => c.program.reduce((n, s) => n + s.lessons.length, 0);
export const courseMinutes = (c: CourseDef) =>
  c.program.reduce((n, s) => n + s.lessons.reduce((k, l) => k + l.minutes, 0), 0);
