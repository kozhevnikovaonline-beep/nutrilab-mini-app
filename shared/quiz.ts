export function isAnswerValue(value: unknown): value is AnswerValue {
  return value === 0 || value === 1 || value === 2;
}

export function isCompleteAnswers(answers: unknown): answers is AnswerValue[] {
  return Array.isArray(answers) && answers.length === QUESTION_COUNT && answers.every(isAnswerValue);
}

export function tierForScore(score: number): ResultTier {
  if (score <= QUIZ_RESULTS.good.range[1]) return 'good';
  if (score <= QUIZ_RESULTS.attention.range[1]) return 'attention';
  return 'priority';
}

export interface QuizScore {
  score: number;
  blockScores: number[];
  tier: ResultTier;
}

export function scoreQuiz(answers: readonly AnswerValue[]): QuizScore {
  if (!isCompleteAnswers(answers)) {
    throw new Error(`Ожидалось ${QUESTION_COUNT} ответов со значениями 0, 1 или 2`);
  }
  const blockScores = QUIZ_BLOCKS.map(() => 0);
  for (const q of QUESTIONS) blockScores[q.blockIndex] += answers[q.index];
  const score = blockScores.reduce((a, b) => a + b, 0);
  return { score, blockScores, tier: tierForScore(score) };
}

/**
 * Блоки, на которые стоит обратить внимание в первую очередь:
 * по убыванию баллов, только с ненулевым результатом, не более `limit`.
 */
export function focusBlocks(blockScores: readonly number[], limit = 2): number[] {
  return blockScores
    .map((score, index) => ({ score, index }))
    .filter((b) => b.score > 0)
    .sort((a, b) => b.score - a.score || a.index - b.index)
    .slice(0, limit)
    .map((b) => b.index);
}
